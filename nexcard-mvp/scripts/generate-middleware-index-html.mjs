#!/usr/bin/env node
// Runs after `vite build`. Fetching /index.html from within Vercel's Edge
// Middleware runtime at request time proved unreliable (self-fetch to the
// same domain consistently returned 403, even with a forwarded User-Agent —
// likely a platform/CDN-level restriction on server-to-server traffic back
// into the same zone). Instead, snapshot the actual built index.html as a JS
// module at build time so middleware.js can rewrite Open Graph tags per
// profile without any runtime fetch.
import fs from 'fs';
import path from 'path';

const root = process.cwd();
const distIndexPath = path.join(root, 'dist', 'index.html');
const outPath = path.join(root, 'middleware-index-html.generated.js');

const html = fs.readFileSync(distIndexPath, 'utf8');

fs.writeFileSync(
  outPath,
  `// Auto-generated by scripts/generate-middleware-index-html.mjs — do not edit.\nmodule.exports = ${JSON.stringify(html)};\n`,
);

console.log(`[generate-middleware-index-html] wrote ${outPath} (${html.length} bytes)`);
